  await page.screenshot({ path: path.join(output, "case-study.png") });
  assert.ok(await page.locator("dialog").getByRole("heading", { name: "AI client onboarding", exact: true }).isVisible());
  await page.keyboard.press("Tab");
  assert.ok(await page.evaluate(() => !!document.activeElement?.closest("dialog")), "Dialog traps keyboard focus");
  await page.keyboard.press("Escape");
  assert.equal(await page.locator("dialog[open]").count(), 0);
  assert.ok(await page.evaluate(() => document.activeElement?.getAttribute("aria-label")?.includes("AI client onboarding")), "Dialog restores trigger focus");
  await page.getByRole("button", { name: "Switch to light theme", exact: true }).click();
